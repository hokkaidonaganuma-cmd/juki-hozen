// テンプレートを「行」に展開。key は記録データの保存キー（テンプレート改訂時も名称ベースで安定）
export function flattenRows(tpl) {
  const rows = [];
  tpl.sections.forEach((sec, si) => {
    sec.items.forEach(([name, parts], ii) => {
      const no = `${si + 1}-${ii + 1}`;
      if (parts && parts.length) {
        parts.forEach((p, pi) => rows.push({ key: `${sec.title}/${name}/${p}`, section: sec.title, sno: si + 1, no, item: name, part: p, first: pi === 0, span: parts.length }));
      } else {
        rows.push({ key: `${sec.title}/${name}`, section: sec.title, sno: si + 1, no, item: name, part: '', first: true, span: 1 });
      }
    });
  });
  return rows;
}

